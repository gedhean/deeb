import React, { useState, useEffect, useRef, Suspense, lazy } from 'react';
import {
  Database as DatabaseIcon,
  RotateCw,
  ChevronDown,
  ChevronUp,
  ExternalLink,
} from 'lucide-react';
import { Link } from 'react-router-dom';
import { Button } from '@/components/ui/button';
import { Input } from '@/components/ui/input';
import { Card, CardContent } from '@/components/ui/card';
import { Skeleton } from '@/components/ui/skeleton';
import { Textarea } from '@/components/ui/textarea';
import {
  Field,
  FieldLabel,
  FieldDescription,
  FieldError,
  FieldContent,
} from '@/components/ui/field';
import type { Database } from '@/lib/api/types';
import type { SQLDialect, EditorTheme } from '@/components/editors';

// Lazy load Monaco Editor
const MonacoSQLEditor = lazy(() =>
  import('@/components/editors').then((module) => ({ default: module.MonacoSQLEditor })),
);

export interface Step2SQLContentAndReviewProps {
  title: string;
  description: string;
  sqlContent: string;
  selectedDatabase: Database | undefined;
  onTitleChange: (title: string) => void;
  onDescriptionChange: (description: string) => void;
  onSQLContentChange: (content: string) => void;
  onRegenerateTitle: () => void;
  onBack: () => void;
  onSubmit: () => void;
  isSubmitting: boolean;
  isTitleAutoGenerated: boolean;
  errors: {
    title?: string;
    sql_content?: string;
  };
  theme: EditorTheme;
  dialect: SQLDialect;
  executionBackend: 'direct' | 'ghost';
  onExecutionBackendChange: (backend: 'direct' | 'ghost') => void;
  ghostEligible: boolean;
}

export const Step2SQLContentAndReview: React.FC<Step2SQLContentAndReviewProps> = ({
  title,
  description,
  sqlContent,
  selectedDatabase,
  onTitleChange,
  onDescriptionChange,
  onSQLContentChange,
  onRegenerateTitle,
  onBack,
  onSubmit,
  isSubmitting,
  isTitleAutoGenerated,
  errors,
  theme,
  dialect,
  executionBackend,
  onExecutionBackendChange,
  ghostEligible,
}) => {
  const [isDescriptionExpanded, setIsDescriptionExpanded] = useState(!!description);
  const editorRef = useRef<HTMLDivElement>(null);

  // Auto-focus on editor when step loads
  useEffect(() => {
    if (editorRef.current) {
      // Give Monaco a moment to mount
      const timer = setTimeout(() => {
        const editorElement = editorRef.current?.querySelector('.monaco-editor');
        if (editorElement) {
          const textarea = editorElement.querySelector('textarea');
          if (textarea) {
            textarea.focus();
          }
        }
      }, 100);
      return () => clearTimeout(timer);
    }
  }, []);

  const isValid = !!title.trim() && title.trim().length <= 255 && !!sqlContent.trim();

  return (
    <div className="space-y-4">
      {/* Title and Description */}
      <div className="space-y-2">
        {/* Title */}
        <Field data-invalid={!!errors.title}>
          <FieldContent>
            <div className="flex items-center justify-between">
              <FieldLabel htmlFor="title">Title</FieldLabel>
              <Button
                type="button"
                variant="ghost"
                size="sm"
                onClick={onRegenerateTitle}
                className={`h-auto py-1 px-2 text-xs ${isTitleAutoGenerated ? 'visible' : 'invisible'}`}
              >
                <RotateCw className="h-3 w-3 mr-1" />
                Regenerate
              </Button>
            </div>
            <Input
              id="title"
              value={title}
              onChange={(e) => onTitleChange(e.target.value)}
              placeholder="Enter a title for this change plan"
              maxLength={255}
              aria-invalid={!!errors.title}
              aria-describedby={errors.title ? 'title-error' : undefined}
              className={isTitleAutoGenerated ? 'text-muted-foreground' : ''}
            />
            {/* {isTitleAutoGenerated && !errors.title && (
              <FieldDescription className="text-xs">
                Title auto-generated from SQL content. You can edit it if needed.
              </FieldDescription>
            )} */}
            <FieldError id="title-error">{errors.title}</FieldError>
          </FieldContent>
        </Field>

        {/* Description (Collapsible) */}
        {!isDescriptionExpanded ? (
          <Button
            type="button"
            variant="ghost"
            size="sm"
            onClick={() => setIsDescriptionExpanded(true)}
            className="h-auto py-1 px-2 text-sm text-muted-foreground hover:text-foreground -mt-2"
          >
            <ChevronDown className="h-4 w-4 mr-1" />+ Add description
          </Button>
        ) : (
          <Field>
            <FieldContent>
              <div className="flex items-center justify-between">
                <FieldLabel htmlFor="description">Description (Optional)</FieldLabel>
                <Button
                  type="button"
                  variant="ghost"
                  size="sm"
                  onClick={() => {
                    setIsDescriptionExpanded(false);
                    onDescriptionChange('');
                  }}
                  className="h-auto py-1 px-2 text-xs"
                >
                  <ChevronUp className="h-3 w-3 mr-1" />
                  Hide
                </Button>
              </div>
              <Textarea
                id="description"
                value={description}
                onChange={(e) => onDescriptionChange(e.target.value)}
                placeholder="Describe the purpose and impact of this change (optional)"
                rows={4}
              />
              <FieldDescription>
                Optional: Describe the purpose and impact of this change.
              </FieldDescription>
            </FieldContent>
          </Field>
        )}
      </div>

      {/* Read-only Summary Cards */}
      <div className="space-y-2">
        <h4 className="text-sm font-medium">Target Database</h4>
        <Card>
          <CardContent className="p-2 pl-3">
            {selectedDatabase ? (
              <div className="flex items-center gap-2">
                <DatabaseIcon className="h-5 w-5 text-primary shrink-0" />
                <div className="flex items-center gap-2 flex-wrap text-sm">
                  <span className="text-muted-foreground">
                    {selectedDatabase.environment?.name || 'Unknown'}
                  </span>
                  <span className="text-muted-foreground">{'>'}</span>
                  <span className="text-muted-foreground">
                    {selectedDatabase.database_instance?.name || 'Unknown'}
                  </span>
                  <span className="text-muted-foreground">{'>'}</span>
                  <Link
                    to={`/databases/${selectedDatabase.id}`}
                    target="_blank"
                    className="text-primary hover:underline inline-flex items-center gap-1 font-medium"
                  >
                    {selectedDatabase.database_name}
                    <ExternalLink className="h-3 w-3" />
                  </Link>
                </div>
              </div>
            ) : (
              <div className="flex items-center gap-3">
                <DatabaseIcon className="h-5 w-5 text-primary" />
                <div className="flex-1">
                  <p className="text-sm font-medium">No database selected</p>
                </div>
              </div>
            )}
          </CardContent>
        </Card>
      </div>

      {/* SQL Content */}
      <Field data-invalid={!!errors.sql_content}>
        <FieldContent>
          <FieldLabel htmlFor="sql-content">SQL Content</FieldLabel>
          <div ref={editorRef}>
            <Suspense fallback={<Skeleton className="w-full h-[400px] rounded-md" />}>
              <MonacoSQLEditor
                value={sqlContent}
                onChange={onSQLContentChange}
                theme={theme}
                dialect={dialect}
                hasError={!!errors.sql_content}
                height={400}
              />
            </Suspense>
          </div>
          <FieldDescription>
            SQL statements will be executed against the target database. Ensure they are correct and
            tested.
          </FieldDescription>
          <FieldError id="sql-content-error">{errors.sql_content}</FieldError>
        </FieldContent>
      </Field>

      {/* Execution backend (ghost executor for eligible DDL plans) */}
      <Field>
        <FieldLabel>Execution backend</FieldLabel>
        <FieldContent>
          <div className="flex items-center gap-4">
            <label className="flex items-center gap-2 text-sm">
              <input
                type="radio"
                name="execution-backend"
                checked={executionBackend === 'direct'}
                onChange={() => onExecutionBackendChange('direct')}
              />
              Direct (transactional SQL)
            </label>
            <label className="flex items-center gap-2 text-sm">
              <input
                type="radio"
                name="execution-backend"
                disabled={!ghostEligible}
                checked={executionBackend === 'ghost'}
                onChange={() => onExecutionBackendChange('ghost')}
              />
              Ghost (gh-ost / pg-online-schema-change)
            </label>
          </div>
          <FieldDescription>
            {ghostEligible
              ? 'Ghost runs DDL through an online schema change tool with a human-gated cutover (single ALTER TABLE per plan).'
              : 'Ghost is available only for DDL plans on databases in non-production environments.'}
          </FieldDescription>
        </FieldContent>
      </Field>

      {/* Actions */}
      <div className="flex items-center justify-between pt-6 border-t">
        <Button type="button" variant="outline" onClick={onBack}>
          Back
        </Button>
        <Button type="button" onClick={onSubmit} disabled={!isValid || isSubmitting}>
          {isSubmitting ? 'Creating...' : 'Create Change Plan'}
        </Button>
      </div>
    </div>
  );
};
