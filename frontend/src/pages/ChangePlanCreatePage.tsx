import React, { useEffect, useState, useMemo } from 'react';
import { useNavigate, useSearchParams } from 'react-router-dom';
import { useTheme } from '@/components/theme-provider';
import { DefaultLayout } from '@/components/layouts';
import { changePlanService } from '@/lib/api/services/changePlans';
import { useDatabases } from '@/hooks/api/useDatabases';
import type { CreateChangePlanRequest, Database, ChangeType } from '@/lib/api/types';
import { APIError } from '@/lib/api/types';
import { Card, CardContent } from '@/components/ui/card';
import { AlertTriangle } from 'lucide-react';
import { showErrorToast } from '@/lib/errorHandling';
import { useCurrentProject } from '@/store';
import type { SQLDialect, EditorTheme } from '@/components/editors';
import {
  StepIndicator,
  Step1Database,
  Step2SQLContentAndReview,
} from '@/components/change-plans/CreateSteps';

import '@/lib/sql-language-setup';
// Preload Monaco Editor for better UX
import('@/components/editors');

// Session storage keys
const FORM_DATA_KEY = 'changePlanCreateFormData';
const STEP_KEY = 'changePlanCreateStep';

interface FormData {
  project_id: string;
  target_database_id: string;
  title: string;
  description: string;
  change_type: ChangeType;
  sql_content: string;
  execution_backend: 'direct' | 'ghost';
}

export const ChangePlanCreatePage: React.FC = () => {
  const navigate = useNavigate();
  const currentProject = useCurrentProject();
  const { theme } = useTheme();
  const [searchParams, setSearchParams] = useSearchParams();

  // Use cached databases from SWR hook with project filter
  const databasesFilter = useMemo(
    () => (currentProject?.id ? { project_id: currentProject.id } : {}),
    [currentProject?.id],
  );
  const { databases, isLoading: isLoadingDatabases } = useDatabases(databasesFilter);

  const [error, setError] = useState('');
  const [isSubmitting, setIsSubmitting] = useState(false);

  // Get initial step from URL or session storage
  const getInitialStep = (): number => {
    // Step 2 requires a selected database — never restore/land there without
    // one (e.g. stale sessionStorage or a hand-crafted ?step=2 URL).
    const storedData = sessionStorage.getItem(FORM_DATA_KEY);
    let hasDatabase = false;
    if (storedData) {
      try {
        hasDatabase = !!JSON.parse(storedData).target_database_id;
      } catch {
        hasDatabase = false;
      }
    }
    if (!hasDatabase) {
      return 1;
    }
    const urlStep = searchParams.get('step');
    if (urlStep === '1' || urlStep === '2') {
      return parseInt(urlStep);
    }
    const storedStep = sessionStorage.getItem(STEP_KEY);
    if (storedStep === '1' || storedStep === '2') {
      return parseInt(storedStep);
    }
    return 1;
  };

  // Get initial form data from session storage or query params
  const getInitialFormData = (): FormData => {
    const stored = sessionStorage.getItem(FORM_DATA_KEY);
    if (stored) {
      try {
        const parsed = JSON.parse(stored);
        // Ensure project_id is set to current project
        parsed.project_id = currentProject?.id || '';
        return parsed;
      } catch {
        // Invalid stored data, return default
      }
    }

    // Check for database_id query parameter
    const databaseIdParam = searchParams.get('database_id');

    return {
      project_id: currentProject?.id || '',
      target_database_id: databaseIdParam || '',
      title: '',
      description: '',
      change_type: 'DDL',
      sql_content: '',
      execution_backend: 'direct',
    };
  };

  const [currentStep, setCurrentStep] = useState(getInitialStep);
  const [formData, setFormData] = useState<FormData>(getInitialFormData);
  const [isTitleAutoGenerated, setIsTitleAutoGenerated] = useState(false);
  const [titleManuallyEdited, setTitleManuallyEdited] = useState(false);
  const [formErrors, setFormErrors] = useState<{
    target_database_id?: string;
    title?: string;
    sql_content?: string;
  }>({});

  // Save form data to session storage whenever it changes
  useEffect(() => {
    sessionStorage.setItem(FORM_DATA_KEY, JSON.stringify(formData));
  }, [formData]);

  // Save current step to session storage and URL
  useEffect(() => {
    sessionStorage.setItem(STEP_KEY, currentStep.toString());
    // Preserve existing query parameters and only update the step
    const newParams = new URLSearchParams(searchParams);
    newParams.set('step', currentStep.toString());
    setSearchParams(newParams, { replace: true });
  }, [currentStep, searchParams, setSearchParams]);

  // Never sit on step 2 without a selected database (e.g. selection cleared
  // while on step 2) — bounce back to step 1.
  useEffect(() => {
    if (currentStep === 2 && !formData.target_database_id) {
      setCurrentStep(1);
    }
  }, [currentStep, formData.target_database_id]);

  // Clear session storage on unmount (successful submission or cancel)
  useEffect(() => {
    return () => {
      // Only clear if navigating away (not on refresh)
      if (performance.navigation.type !== 1) {
        sessionStorage.removeItem(FORM_DATA_KEY);
        sessionStorage.removeItem(STEP_KEY);
      }
    };
  }, []);

  // Redirect if no project is selected. Show a toast so the redirect is not
  // silent (router state alone was never rendered anywhere).
  useEffect(() => {
    if (!currentProject) {
      showErrorToast('Please select a project first');
      navigate('/dashboard');
    }
  }, [currentProject, navigate]);

  // Generate a suitable title from SQL content
  const generateTitle = (
    sqlContent: string,
    changeType: ChangeType,
    databases: Database[],
    targetDatabaseId: string,
  ): string => {
    const sql = sqlContent.trim().toUpperCase();

    // Extract first SQL keyword
    const sqlKeywords = [
      'CREATE',
      'ALTER',
      'DROP',
      'INSERT',
      'UPDATE',
      'DELETE',
      'SELECT',
      'TRUNCATE',
    ];
    let action = '';
    let objectName = '';

    for (const keyword of sqlKeywords) {
      if (sql.startsWith(keyword)) {
        action = keyword;
        break;
      }
    }

    // Try to extract table/object name (basic pattern matching)
    if (action) {
      // Pattern: CREATE TABLE table_name
      const tableMatch = sql.match(
        /(?:CREATE|ALTER|DROP|TRUNCATE)\s+(?:TABLE|INDEX|VIEW|SEQUENCE|FUNCTION|PROCEDURE)\s+([A-Z_][A-Z0-9_]*)/i,
      );
      if (tableMatch) {
        objectName = tableMatch[1];
      } else {
        // Pattern: INSERT INTO table_name
        const insertMatch = sql.match(/INSERT\s+INTO\s+([A-Z_][A-Z0-9_]*)/i);
        if (insertMatch) {
          objectName = insertMatch[1];
        } else {
          // Pattern: UPDATE table_name
          const updateMatch = sql.match(/UPDATE\s+([A-Z_][A-Z0-9_]*)/i);
          if (updateMatch) {
            objectName = updateMatch[1];
          } else {
            // Pattern: DELETE FROM table_name
            const deleteMatch = sql.match(/DELETE\s+FROM\s+([A-Z_][A-Z0-9_]*)/i);
            if (deleteMatch) {
              objectName = deleteMatch[1];
            }
          }
        }
      }
    }

    // Get database name if available
    const selectedDatabase = databases.find((db) => db.id === targetDatabaseId);
    const dbName = selectedDatabase?.database_name || '';
    const date = new Date().toLocaleString('en-US', {
      month: 'short',
      day: 'numeric',
      year: 'numeric',
      hour: '2-digit',
      minute: '2-digit',
    });

    // Build title
    let title = '';
    if (action && objectName) {
      title = `${action} ${objectName}`;
      if (dbName) {
        title = `[${dbName}] ${title}`;
      }
    } else if (action) {
      title = `${action} statement`;
      if (dbName) {
        title = `[${dbName}] ${title}`;
      }
    } else if (changeType === 'DDL') {
      title = dbName ? `[${dbName}] DDL Change` : 'DDL Change';
    } else {
      title = dbName ? `[${dbName}] DML Change` : 'DML Change';
    }

    title += ` @ ${date}`;

    // Limit to 255 characters
    return title.length > 255 ? title.substring(0, 252) + '...' : title;
  };

  // Validate current step
  const validateStep = (step: number): boolean => {
    const errors: {
      target_database_id?: string;
      title?: string;
      sql_content?: string;
    } = {};

    if (step === 1) {
      if (!formData.target_database_id) {
        errors.target_database_id = 'Target database is required';
      }
    }

    if (step === 2) {
      // Step 2 also requires a target database (in case user lands directly on step 2)
      if (!formData.target_database_id) {
        errors.target_database_id = 'Target database is required';
      }

      if (!formData.title.trim()) {
        errors.title = 'Title is required';
      } else if (formData.title.trim().length > 255) {
        errors.title = 'Title must be 255 characters or less';
      }

      if (!formData.sql_content.trim()) {
        errors.sql_content = 'SQL content is required';
      }
    }

    setFormErrors(errors);
    return Object.keys(errors).length === 0;
  };

  // Get SQL dialect based on selected database
  const getSQLDialect = (): SQLDialect => {
    const selectedDatabase = databases.find((db) => db.id === formData.target_database_id);
    if (!selectedDatabase?.database_instance?.database_engine) {
      return 'mysql'; // Default to MySQL
    }
    const dbEngine = selectedDatabase.database_instance.database_engine.toLowerCase();
    return dbEngine === 'postgres' || dbEngine === 'postgresql' ? 'pgsql' : 'mysql';
  };

  // Get editor theme based on system theme
  const getEditorTheme = (): EditorTheme => {
    return theme === 'dark' ? 'dark' : 'light';
  };

  // Handle step navigation
  const handleNext = () => {
    if (validateStep(currentStep)) {
      // When moving from step 1 to step 2, generate title if needed
      if (currentStep === 1 && formData.sql_content.trim() && !titleManuallyEdited) {
        const newTitle = generateTitle(
          formData.sql_content,
          formData.change_type,
          databases,
          formData.target_database_id,
        );
        setFormData((prev) => ({ ...prev, title: newTitle }));
        setIsTitleAutoGenerated(true);
      }
      setCurrentStep(2);
      setError('');
    }
  };

  const handleBack = () => {
    setCurrentStep(1);
    setError('');
  };

  // Handle form field changes
  const handleDatabaseChange = (databaseId: string) => {
    setFormData((prev) => ({ ...prev, target_database_id: databaseId }));
    setFormErrors((prev) => ({ ...prev, target_database_id: undefined }));
  };

  const handleTitleChange = (title: string) => {
    setFormData((prev) => ({ ...prev, title }));
    setTitleManuallyEdited(true);
    setIsTitleAutoGenerated(false);
    setFormErrors((prev) => ({ ...prev, title: undefined }));
  };

  const handleDescriptionChange = (description: string) => {
    setFormData((prev) => ({ ...prev, description }));
  };

  const handleSQLContentChange = (sqlContent: string) => {
    setFormData((prev) => {
      const updated = { ...prev, sql_content: sqlContent };
      // Auto-generate title when SQL content changes (only if not manually edited)
      if (sqlContent.trim() && updated.target_database_id && !titleManuallyEdited) {
        updated.title = generateTitle(
          sqlContent,
          updated.change_type,
          databases,
          updated.target_database_id,
        );
        setIsTitleAutoGenerated(true);
      }
      return updated;
    });
    setFormErrors((prev) => ({ ...prev, sql_content: undefined }));
  };

  const handleRegenerateTitle = () => {
    if (formData.sql_content.trim() && formData.target_database_id) {
      const newTitle = generateTitle(
        formData.sql_content,
        formData.change_type,
        databases,
        formData.target_database_id,
      );
      setFormData((prev) => ({ ...prev, title: newTitle }));
      setIsTitleAutoGenerated(true);
      setTitleManuallyEdited(false);
    }
  };

  // Handle submit
  const handleSubmit = async () => {
    // Validate all required fields (step 2 validation includes target_database_id check)
    if (!validateStep(2)) {
      return;
    }

    try {
      setIsSubmitting(true);
      const createData: CreateChangePlanRequest = {
        project_id: formData.project_id,
        target_database_id: formData.target_database_id,
        title: formData.title.trim(),
        description: formData.description?.trim() || '',
        change_type: formData.change_type,
        sql_content: formData.sql_content.trim(),
        execution_backend: ghostEligible ? formData.execution_backend : 'direct',
      };

      const createdChangePlan = await changePlanService.createChangePlan(createData);

      // Clear session storage on successful submission
      sessionStorage.removeItem(FORM_DATA_KEY);
      sessionStorage.removeItem(STEP_KEY);

      // Redirect to change plan detail page
      navigate(`/change-plans/${createdChangePlan.id}`);
    } catch (err) {
      if (err instanceof APIError) {
        setError(err.message);
      } else {
        setError('Failed to create change plan. Please try again.');
      }
      console.error('Failed to create change plan:', err);
    } finally {
      setIsSubmitting(false);
    }
  };

  const handleCancel = () => {
    // Clear session storage on cancel
    sessionStorage.removeItem(FORM_DATA_KEY);
    sessionStorage.removeItem(STEP_KEY);
    navigate(-1);
  };

  const selectedDatabase = databases.find((db) => db.id === formData.target_database_id);

  // Ghost executor is available for DDL plans on databases with an
  // environment assigned (server enforces this too).
  const selectedDatabaseInstance = selectedDatabase?.database_instance;
  const selectedEngine = selectedDatabaseInstance?.database_engine;

  // Online Migrator executor is available only for MySQL DDL plans on
  // databases with an environment assigned (server enforces this too,
  // fail-closed; production environments are allowed). Collect the specific
  // failing rules so the UI can show exactly why the selector is disabled.
  const ghostIneligibilityReasons: string[] = [];
  if (formData.change_type !== 'DDL') {
    ghostIneligibilityReasons.push(
      `Online Migrator requires change type DDL (selected: ${formData.change_type}).`,
    );
  }
  if (selectedEngine !== 'mysql') {
    ghostIneligibilityReasons.push(
      `Online Migrator requires a MySQL database${
        selectedEngine ? ` (selected: ${selectedEngine})` : ''
      }.`,
    );
  }
  if (!selectedDatabase?.environment) {
    if (selectedDatabase) {
      ghostIneligibilityReasons.push(
        'Online Migrator requires the database to have an environment assigned.',
      );
    }
  }
  const ghostEligible = ghostIneligibilityReasons.length === 0;

  const steps = [
    { label: 'Target Database', description: 'Select database' },
    { label: 'SQL Content & Submit', description: 'Write SQL and submit' },
  ];

  return (
    <DefaultLayout
      breadcrumbs={[
        { label: 'Change Plans', href: '/change-plans' },
        { label: 'Create', isCurrentPage: true },
      ]}
    >
      <div className="space-y-6">
        {/* Header */}
        <div>
          <h1 className="text-3xl font-bold tracking-tight">Create Change Plan</h1>
          <p className="text-muted-foreground mt-1">
            Create a new database change plan with SQL content
          </p>
        </div>

        {/* Step Indicator */}
        <StepIndicator currentStep={currentStep} totalSteps={2} steps={steps} />

        {/* Error message */}
        {error && (
          <Card className="border-destructive">
            <CardContent className="pt-6">
              <div className="flex items-center gap-2 text-destructive">
                <AlertTriangle className="h-4 w-4" />
                <span className="text-sm">{error}</span>
              </div>
            </CardContent>
          </Card>
        )}

        {/* Form */}
        <Card>
          <CardContent className="p-6">
            {currentStep === 1 ? (
              <Step1Database
                databases={databases}
                isLoadingDatabases={isLoadingDatabases}
                selectedDatabaseId={formData.target_database_id}
                onDatabaseChange={handleDatabaseChange}
                onNext={handleNext}
                onCancel={handleCancel}
                error={formErrors.target_database_id}
              />
            ) : (
              <Step2SQLContentAndReview
                title={formData.title}
                description={formData.description}
                sqlContent={formData.sql_content}
                selectedDatabase={selectedDatabase}
                onTitleChange={handleTitleChange}
                onDescriptionChange={handleDescriptionChange}
                onSQLContentChange={handleSQLContentChange}
                onRegenerateTitle={handleRegenerateTitle}
                onBack={handleBack}
                onSubmit={handleSubmit}
                isSubmitting={isSubmitting}
                isTitleAutoGenerated={isTitleAutoGenerated}
                errors={formErrors}
                theme={getEditorTheme()}
                dialect={getSQLDialect()}
                executionBackend={formData.execution_backend}
                onExecutionBackendChange={(backend) =>
                  setFormData((prev) => ({ ...prev, execution_backend: backend }))
                }
                ghostEligible={ghostEligible}
                ghostIneligibilityReasons={ghostIneligibilityReasons}
              />
            )}
          </CardContent>
        </Card>
      </div>
    </DefaultLayout>
  );
};
