import type { StateCreator } from 'zustand';
import type { ChangeType } from '@/lib/api/types';

export interface ChangePlanFormData {
  project_id: string;
  target_database_id: string;
  title: string;
  description: string;
  change_type: ChangeType;
  sql_content: string;
}

export interface ChangePlanFormSlice {
  // Form state
  changePlanFormData: ChangePlanFormData | null;
  changePlanFormStep: number;
  changePlanFormTitleAutoGenerated: boolean;
  changePlanFormTitleManuallyEdited: boolean;

  // Actions
  setChangePlanFormData: (data: Partial<ChangePlanFormData>) => void;
  setChangePlanFormStep: (step: number) => void;
  setChangePlanFormTitleAutoGenerated: (value: boolean) => void;
  setChangePlanFormTitleManuallyEdited: (value: boolean) => void;
  resetChangePlanForm: () => void;
  initializeChangePlanForm: (projectId: string) => void;
}

const getDefaultFormData = (projectId: string): ChangePlanFormData => ({
  project_id: projectId,
  target_database_id: '',
  title: '',
  description: '',
  change_type: 'DDL',
  sql_content: '',
});

export const createChangePlanFormSlice: StateCreator<
  ChangePlanFormSlice,
  [],
  [],
  ChangePlanFormSlice
> = (set) => ({
  // Initial state
  changePlanFormData: null,
  changePlanFormStep: 1,
  changePlanFormTitleAutoGenerated: false,
  changePlanFormTitleManuallyEdited: false,

  // Update form data (merge with existing)
  setChangePlanFormData: (data) =>
    set((state) => ({
      changePlanFormData: state.changePlanFormData
        ? { ...state.changePlanFormData, ...data }
        : getDefaultFormData(data.project_id || ''),
    })),

  // Set current step
  setChangePlanFormStep: (step) =>
    set({
      changePlanFormStep: step,
    }),

  // Set title auto-generated flag
  setChangePlanFormTitleAutoGenerated: (value) =>
    set({
      changePlanFormTitleAutoGenerated: value,
    }),

  // Set title manually edited flag
  setChangePlanFormTitleManuallyEdited: (value) =>
    set({
      changePlanFormTitleManuallyEdited: value,
    }),

  // Reset form to initial state
  resetChangePlanForm: () =>
    set({
      changePlanFormData: null,
      changePlanFormStep: 1,
      changePlanFormTitleAutoGenerated: false,
      changePlanFormTitleManuallyEdited: false,
    }),

  // Initialize form with project ID
  initializeChangePlanForm: (projectId) =>
    set({
      changePlanFormData: getDefaultFormData(projectId),
      changePlanFormStep: 1,
      changePlanFormTitleAutoGenerated: false,
      changePlanFormTitleManuallyEdited: false,
    }),
});
