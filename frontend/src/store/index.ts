import { create } from 'zustand';
import { devtools, persist } from 'zustand/middleware';
import { createOrganizationSlice, type OrganizationSlice } from './slices/organizationSlice';
import { createProjectSlice, type ProjectSlice } from './slices/projectSlice';
import { createAuthSlice, type AuthSlice } from './slices/authSlice';
import { createUsersSlice, type UsersSlice } from './slices/usersSlice';
import { createProjectsSlice, type ProjectsSlice } from './slices/projectsSlice';
import { createDatabasesSlice, type DatabasesSlice } from './slices/databasesSlice';
import { createChangePlanFormSlice, type ChangePlanFormSlice } from './slices/changePlanFormSlice';

// Combined store type
export type AppStore = OrganizationSlice &
  ProjectSlice &
  AuthSlice &
  UsersSlice &
  ProjectsSlice &
  DatabasesSlice &
  ChangePlanFormSlice;

// Create the store with combined slices
// Following Zustand best practices: https://github.com/pmndrs/zustand/blob/main/docs/guides/slices-pattern.md
export const useAppStore = create<AppStore>()(
  devtools(
    persist(
      (...a) => ({
        ...createOrganizationSlice(...a),
        ...createProjectSlice(...a),
        ...createAuthSlice(...a),
        ...createUsersSlice(...a),
        ...createProjectsSlice(...a),
        ...createDatabasesSlice(...a),
        ...createChangePlanFormSlice(...a),
      }),
      {
        name: 'deeb-app-store',
        // Only persist specific fields to avoid storing sensitive data
        // Note: Auth state (user) is NOT persisted - tokens are in HttpOnly cookies
        partialize: (state) => ({
          currentProject: state.currentProject,
          organization: state.organization,
          // Cache users, projects, and databases with timestamps for TTL
          users: state.users,
          usersLastFetchedAt: state.usersLastFetchedAt,
          projects: state.projects,
          projectsLastFetchedAt: state.projectsLastFetchedAt,
          databases: state.databases,
          databasesLastFetchedAt: state.databasesLastFetchedAt,
          // Change plan form state (for multi-step form persistence)
          changePlanFormData: state.changePlanFormData,
          changePlanFormStep: state.changePlanFormStep,
          changePlanFormTitleAutoGenerated: state.changePlanFormTitleAutoGenerated,
          changePlanFormTitleManuallyEdited: state.changePlanFormTitleManuallyEdited,
          // Explicitly exclude auth state from persistence
        }),
      },
    ),
    {
      name: 'DeebAppStore',
    },
  ),
);

