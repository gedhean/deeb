// Export a function to clear all state (useful for logout)
export const useClearAllState = () => {
  const clearOrganization = useClearOrganization();
  const clearCurrentProject = useClearCurrentProject();
  const logout = useLogout();
  const clearUsers = useClearUsers();
  const clearProjects = useClearProjects();
  const clearDatabases = useClearDatabases();
  const resetChangePlanForm = useResetChangePlanForm();

  return () => {
    clearOrganization();
    clearCurrentProject();
    logout();
    clearUsers();
    clearProjects();
    clearDatabases();
    resetChangePlanForm();
  };
};
