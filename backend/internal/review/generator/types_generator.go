package main

import (
	"bytes"
	"fmt"
	"os"
	"sort"
	"strings"
	"text/template"
)

// GenerateTypeScriptTypes generates the TypeScript types file
func GenerateTypeScriptTypes(rules []ParsedRule, outputPath string) error {
	// Sort rules by category then type
	sort.Slice(rules, func(i, j int) bool {
		if rules[i].Category == rules[j].Category {
			return rules[i].Type < rules[j].Type
		}
		return rules[i].Category < rules[j].Category
	})

	// Group rules by engine and category
	rulesByEngineAndCategory := make(map[string]map[string][]ParsedRule)
	for _, rule := range rules {
		var engines []string
		if rule.Engine == "both" {
			engines = []string{"mysql", "postgres"}
		} else {
			engines = []string{rule.Engine}
		}

		for _, engine := range engines {
			if rulesByEngineAndCategory[engine] == nil {
				rulesByEngineAndCategory[engine] = make(map[string][]ParsedRule)
			}
			rulesByEngineAndCategory[engine][rule.Category] = append(
				rulesByEngineAndCategory[engine][rule.Category],
				rule,
			)
		}
	}

	// Extract all unique rule types
	ruleTypes := []string{}
	for _, rule := range rules {
		ruleTypes = append(ruleTypes, rule.Type)
	}
	sort.Strings(ruleTypes)

	// Extract all unique categories
	categorySet := make(map[string]bool)
	for _, rule := range rules {
		categorySet[rule.Category] = true
	}
	categories := []string{}
	for cat := range categorySet {
		categories = append(categories, cat)
	}
	sort.Strings(categories)

	// Prepare template data
	data := struct {
		Rules                    []ParsedRule
		RuleTypes                []string
		Categories               []string
		RulesByEngineAndCategory map[string]map[string][]ParsedRule
	}{
		Rules:                    rules,
		RuleTypes:                ruleTypes,
		Categories:               categories,
		RulesByEngineAndCategory: rulesByEngineAndCategory,
	}

	// Execute template
	tmpl := template.Must(template.New("typescript").Funcs(tsTemplateFuncs()).Parse(typescriptTemplate))
	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, data); err != nil {
		return fmt.Errorf("failed to execute template: %w", err)
	}

	// Write to file
	if err := os.WriteFile(outputPath, buf.Bytes(), 0o644); err != nil {
		return fmt.Errorf("failed to write output file: %w", err)
	}

	return nil
}

// tsTemplateFuncs returns custom template functions for TypeScript generation
func tsTemplateFuncs() template.FuncMap {
	return template.FuncMap{
		"tsQuote": func(s string) string {
			// Escape single quotes
			s = strings.ReplaceAll(s, "'", "\\'")
			return fmt.Sprintf("'%s'", s)
		},
		"tsFormatDefault": func(v interface{}) string {
			if v == nil {
				return "undefined"
			}
			switch val := v.(type) {
			case string:
				return fmt.Sprintf("'%s'", strings.ReplaceAll(val, "'", "\\'"))
			case []interface{}:
				if len(val) == 0 {
					return "[]"
				}
				parts := []string{}
				for _, item := range val {
					parts = append(parts, fmt.Sprintf("'%s'", item))
				}
				return fmt.Sprintf("[%s]", strings.Join(parts, ", "))
			case int, int32, int64, float64:
				return fmt.Sprintf("%v", val)
			case bool:
				return fmt.Sprintf("%v", val)
			default:
				return fmt.Sprintf("%v", val)
			}
		},
		"tsComment": func(s string) string {
			// Escape for JSDoc comments
			s = strings.ReplaceAll(s, "*/", "*\\/")
			return s
		},
	}
}

const typescriptTemplate = `// Code generated by internal/review/generator/main.go. DO NOT EDIT.
// Source: github.com/nsxbet/sql-reviewer config/schema.yaml

/**
 * Rule parameter type
 */
export type RuleParameterType =
  | 'STRING'
  | 'NUMBER'
  | 'BOOLEAN'
  | 'STRING_ARRAY'
  | 'TEMPLATE';

/**
 * Rule parameter definition
 */
export interface RuleParameter {
  name: string;
  type: RuleParameterType;
  description: string;
  required: boolean;
  default?: any;
  templateList?: string[];
}

/**
 * SQL review rule metadata
 */
export interface RuleMetadata {
  type: string;
  name: string;
  description: string;
  category: string;
  engine: 'mysql' | 'postgres' | 'both';
  parameters: RuleParameter[];
}

/**
 * Rules catalog organized by engine and category
 */
export interface RulesCatalog {
  [engine: string]: {
    [category: string]: RuleMetadata[];
  };
}

/**
 * Rule type literal union
 */
export type RuleType =
{{- range $i, $ruleType := .RuleTypes }}
  | {{ tsQuote $ruleType }}
{{- end }};

/**
 * Rule category literal union
 */
export type RuleCategory =
{{- range $i, $category := .Categories }}
  | {{ tsQuote $category }}
{{- end }};

/**
 * Complete rules catalog
 */
export const RULES_CATALOG: RulesCatalog = {
{{- range $engine, $categories := .RulesByEngineAndCategory }}
  {{ tsQuote $engine }}: {
  {{- range $category, $rules := $categories }}
    {{ tsQuote $category }}: [
    {{- range $rule := $rules }}
      {
        type: {{ tsQuote $rule.Type }},
        name: {{ tsQuote $rule.Name }},
        description: {{ tsQuote $rule.Description }},
        category: {{ tsQuote $rule.Category }},
        engine: {{ tsQuote $rule.Engine }},
        parameters: [
        {{- range $param := $rule.Parameters }}
          {
            name: {{ tsQuote $param.Name }},
            type: {{ tsQuote $param.Type }},
            description: {{ tsQuote $param.Description }},
            required: {{ $param.Required }},
            {{- if $param.Default }}
            default: {{ tsFormatDefault $param.Default }},
            {{- end }}
            {{- if $param.TemplateList }}
            templateList: [{{ range $i, $t := $param.TemplateList }}{{ if $i }}, {{ end }}{{ tsQuote $t }}{{ end }}],
            {{- end }}
          },
        {{- end }}
        ],
      },
    {{- end }}
    ],
  {{- end }}
  },
{{- end }}
};

/**
 * Rules index for quick lookup by rule type
 */
export const RULES_INDEX: Record<string, RuleMetadata> = {
{{- range $rule := .Rules }}
  {{ tsQuote $rule.Type }}: {
    type: {{ tsQuote $rule.Type }},
    name: {{ tsQuote $rule.Name }},
    description: {{ tsQuote $rule.Description }},
    category: {{ tsQuote $rule.Category }},
    engine: {{ tsQuote $rule.Engine }},
    parameters: [
    {{- range $param := $rule.Parameters }}
      {
        name: {{ tsQuote $param.Name }},
        type: {{ tsQuote $param.Type }},
        description: {{ tsQuote $param.Description }},
        required: {{ $param.Required }},
        {{- if $param.Default }}
        default: {{ tsFormatDefault $param.Default }},
        {{- end }}
        {{- if $param.TemplateList }}
        templateList: [{{ range $i, $t := $param.TemplateList }}{{ if $i }}, {{ end }}{{ tsQuote $t }}{{ end }}],
        {{- end }}
      },
    {{- end }}
    ],
  },
{{- end }}
};

/**
 * Get rule metadata by rule type
 */
export function getRuleMetadata(ruleType: string): RuleMetadata | undefined {
  return RULES_INDEX[ruleType];
}

/**
 * Get rules by engine and category
 */
export function getRulesByCategory(
  engine: 'mysql' | 'postgres',
  category: string
): RuleMetadata[] {
  return RULES_CATALOG[engine]?.[category] || [];
}

/**
 * Get all rule types
 */
export function getAllRuleTypes(): string[] {
  return Object.keys(RULES_INDEX);
}

/**
 * Validate if a rule type exists
 */
export function validateRuleType(ruleType: string): boolean {
  return ruleType in RULES_INDEX;
}

/**
 * Get all categories for an engine
 */
export function getCategories(engine: 'mysql' | 'postgres'): string[] {
  return Object.keys(RULES_CATALOG[engine] || {});
}

/**
 * Get all rules for an engine
 */
export function getAllRules(engine: 'mysql' | 'postgres'): RuleMetadata[] {
  const categories = RULES_CATALOG[engine] || {};
  const rules: RuleMetadata[] = [];
  for (const categoryRules of Object.values(categories)) {
    rules.push(...categoryRules);
  }
  return rules;
}
`
