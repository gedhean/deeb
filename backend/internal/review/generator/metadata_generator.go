// GenerateGoMetadata generates the rules_metadata.go file
func GenerateGoMetadata(rules []ParsedRule, outputPath string) error {
	// Sort rules by category then type
	sort.Slice(rules, func(i, j int) bool {
		if rules[i].Category == rules[j].Category {
			return rules[i].Type < rules[j].Type
		}
		return rules[i].Category < rules[j].Category
	})

	// Group rules by engine and category
	rulesByEngineAndCategory := make(map[string]map[string][]ParsedRule)
	for _, rule := range rules {
		var engines []string
		if rule.Engine == "both" {
			engines = []string{"mysql", "postgres"}
		} else {
			engines = []string{rule.Engine}
		}

		for _, engine := range engines {
			if rulesByEngineAndCategory[engine] == nil {
				rulesByEngineAndCategory[engine] = make(map[string][]ParsedRule)
			}
			rulesByEngineAndCategory[engine][rule.Category] = append(
				rulesByEngineAndCategory[engine][rule.Category],
				rule,
			)
		}
	}

	// Prepare template data
	data := struct {
		Rules                    []ParsedRule
		RulesByEngineAndCategory map[string]map[string][]ParsedRule
	}{
		Rules:                    rules,
		RulesByEngineAndCategory: rulesByEngineAndCategory,
	}

	// Execute template
	tmpl := template.Must(template.New("metadata").Funcs(templateFuncs()).Parse(metadataTemplate))
	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, data); err != nil {
		return fmt.Errorf("failed to execute template: %w", err)
	}

	// Format Go code
	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		// Write unformatted code for debugging
		_ = os.WriteFile(outputPath+".unformatted", buf.Bytes(), 0o644)
		return fmt.Errorf("failed to format generated code: %w", err)
	}

	// Write to file
	if err := os.WriteFile(outputPath, formatted, 0o644); err != nil {
		return fmt.Errorf("failed to write output file: %w", err)
	}

	return nil
}

// templateFuncs returns custom template functions
func templateFuncs() template.FuncMap {
	return template.FuncMap{
		"quote": func(s string) string {
			return fmt.Sprintf("%q", s)
		},
		"formatDefault": func(v interface{}) string {
			if v == nil {
				return "nil"
			}
			switch val := v.(type) {
			case string:
				return fmt.Sprintf("%q", val)
			case []interface{}:
				if len(val) == 0 {
					return "[]string{}"
				}
				parts := []string{}
				for _, item := range val {
					parts = append(parts, fmt.Sprintf("%q", item))
				}
				return fmt.Sprintf("[]string{%s}", strings.Join(parts, ", "))
			case int, int32, int64:
				return fmt.Sprintf("%d", val)
			case float64:
				return fmt.Sprintf("%v", val)
			case bool:
				return fmt.Sprintf("%v", val)
			default:
				return fmt.Sprintf("%v", val)
			}
		},
		"capitalize": func(s string) string {
			if s == "" {
				return ""
			}
			return strings.ToUpper(s[:1]) + s[1:]
		},
	}
}

