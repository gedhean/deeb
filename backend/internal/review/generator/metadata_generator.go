// GetAvailableRules returns all available SQL review rules
// organized by engine and category
func GetAvailableRules() map[string]map[string][]RuleMetadata {
	return rulesCatalog
}

// GetRuleMetadata returns metadata for a specific rule type
func GetRuleMetadata(ruleType string) (*RuleMetadata, bool) {
	metadata, ok := rulesIndex[ruleType]
	return metadata, ok
}

// GetRulesByCategory returns all rules for a specific engine and category
func GetRulesByCategory(engine, category string) []RuleMetadata {
	if categories, ok := rulesCatalog[engine]; ok {
		if rules, ok := categories[category]; ok {
			return rules
		}
	}
	return nil
}

// GetAllRuleTypes returns a list of all available rule types
func GetAllRuleTypes() []string {
	types := make([]string, 0, len(rulesIndex))
	for ruleType := range rulesIndex {
		types = append(types, ruleType)
	}
	return types
}

// ValidateRuleType checks if a rule type exists
func ValidateRuleType(ruleType string) bool {
	_, ok := rulesIndex[ruleType]
	return ok
}

